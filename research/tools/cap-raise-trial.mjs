#!/usr/bin/env node
/**
 * The cap decision, measured end to end.
 *
 * `data/build.mjs` keeps 100 words per reading. The cap's own justification was
 * file size and grid-search time; `cap-scope.mjs` shows what it deletes (595
 * entries across 15 single-syllable readings, all tied at the model's floor
 * score). This closes the loop: rebuild with the cap effectively removed, then
 * ask the real engine how many *new characters* become typable and what the
 * file size and load time actually cost.
 *
 * Writes to a temporary file. It does not touch data/bopomofo-lm.tsv — the
 * shipped model is regenerated by data/build.mjs alone.
 *
 * usage: node cap-raise-trial.mjs [--caps 100,200,100000]
 */
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync, statSync, existsSync, unlinkSync } from "node:fs";
import { fileURLToPath, pathToFileURL } from "node:url";
import { dirname, join } from "node:path";
import { Dictionary } from "../../engine/src/dictionary.ts";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..", "..");
const vendorDir = join(root, "data", "vendor");
const SHIPPED = join(root, "data", "bopomofo-lm.tsv");

const argIdx = process.argv.indexOf("--caps");
const CAPS = argIdx >= 0 ? process.argv[argIdx + 1].split(",").map(Number) : [100, 128, 150, 200, 1000];
const argIdx2 = process.argv.indexOf("--loaders");
const LOADERS = argIdx2 >= 0 ? process.argv[argIdx2 + 1].split(",").map(Number) : [128, 200];

const CONSONANTS = ["", "ㄅ", "ㄆ", "ㄇ", "ㄈ", "ㄉ", "ㄊ", "ㄋ", "ㄌ", "ㄍ", "ㄎ", "ㄏ",
  "ㄐ", "ㄑ", "ㄒ", "ㄓ", "ㄔ", "ㄕ", "ㄖ", "ㄗ", "ㄘ", "ㄙ"];
const MIDDLES = ["", "ㄧ", "ㄨ", "ㄩ"];
const VOWELS = ["", "ㄚ", "ㄛ", "ㄜ", "ㄝ", "ㄞ", "ㄟ", "ㄠ", "ㄡ", "ㄢ", "ㄣ", "ㄤ", "ㄥ", "ㄦ"];
const TONES = ["", "ˊ", "ˇ", "ˋ", "˙"];
const decodeSyllable = (p) => {
  const o = p.charCodeAt(0) - 48 + (p.charCodeAt(1) - 48) * 79;
  return CONSONANTS[o % 22] + MIDDLES[Math.floor(o / 22) % 4] + VOWELS[Math.floor(o / 88) % 14] + TONES[Math.floor(o / 1232) % 5];
};
const decodeKey = (k) => {
  if (k.length % 2) return null;
  const out = [];
  for (let i = 0; i < k.length; i += 2) { const s = decodeSyllable(k.slice(i, i + 2)); if (!s) return null; out.push(s); }
  return out.join("-");
};

const src = readFileSync(join(vendorDir, "WebData.ts"), "utf8");
const tmp = join(vendorDir, ".cap-trial.gen.mjs");
writeFileSync(tmp, src);
const { webData } = await import(pathToFileURL(tmp).href);
if (existsSync(tmp)) unlinkSync(tmp);

const upstream = new Map();
for (const [key, value] of Object.entries(webData)) {
  if (key.startsWith("_")) continue;
  const reading = decodeKey(key);
  if (!reading) continue;
  const toks = value.split(" ");
  if (toks.length % 2) continue;
  let list = upstream.get(reading);
  if (!list) { list = []; upstream.set(reading, list); }
  for (let i = 0; i + 1 < toks.length; i += 2) {
    const word = toks[i];
    const score = Number.parseFloat(toks[i + 1]);
    if (!word || word.startsWith("MACRO@") || !Number.isFinite(score)) continue;
    list.push({ word, score });
  }
}

const render = (cap) => {
  const rows = [];
  for (const [reading, list] of upstream) {
    list.sort((a, b) => b.score - a.score);
    // Dedupe before capping, exactly as data/build.mjs does: the cap counts
    // distinct words, not rows. Deduping only inside the slice would let
    // duplicates earlier in the list push real characters out of the last slot.
    const seen = new Set();
    const distinct = [];
    for (const x of list) {
      if (seen.has(x.word)) continue;
      seen.add(x.word);
      distinct.push(x);
    }
    for (const x of distinct.slice(0, cap)) rows.push(`${reading}\t${x.word}\t${x.score}`);
  }
  rows.sort();
  return "# reading<TAB>word<TAB>log10_prob\n" + rows.join("\n") + "\n";
};

/** characters the user can actually get from some single-syllable reading */
function typableChars(text) {
  const dict = Dictionary.fromText(text, "<trial>");
  const out = new Set();
  for (const [reading, entries] of dict["byReading"] ?? []) void reading;
  for (const reading of dict.readings) {
    if (reading.includes("-")) continue;
    for (const e of dict.lookup(reading)) for (const ch of e.word) out.add(ch);
  }
  return out;
}

const shippedChars = typableChars(readFileSync(SHIPPED, "utf8"));
console.log(`shipped file       ${statSync(SHIPPED).size} bytes   ${shippedChars.size} distinct characters in single-syllable readings`);
console.log();
console.log("data cap  loader  rows      bytes    +bytes   load ms   new chars");
for (const cap of CAPS) {
  const text = render(cap);
  const bytes = Buffer.byteLength(text);
  for (const loader of LOADERS) {
    const t0 = process.hrtime.bigint();
    const dict = Dictionary.fromText(text, `<cap${cap}/loader${loader}>`, { maxCandidatesPerReading: loader });
    const loadMs = Number(process.hrtime.bigint() - t0) / 1e6;
    const out = new Set();
    for (const reading of dict.readings) {
      if (reading.includes("-")) continue;
      for (const e of dict.lookup(reading)) for (const ch of e.word) out.add(ch);
    }
    let added = 0;
    for (const ch of out) if (!shippedChars.has(ch)) added++;
    const rows = text.split("\n").length - 2;
    console.log(`${String(cap).padEnd(9)} ${String(loader).padStart(6)} ${String(rows).padStart(7)} ${String(bytes).padStart(10)} ${(bytes - statSync(SHIPPED).size >= 0 ? "+" : "") + String(bytes - statSync(SHIPPED).size).padStart(8)} ${loadMs.toFixed(0).padStart(9)} ${String(added).padStart(10)}`);
  }
}
void execFileSync;
